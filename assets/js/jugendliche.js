function likeCount(id){
  // deterministic pseudo-count so numbers feel populated, plus 1 if user liked it
  let hash = 0;
  for(let i=0;i<id.length;i++){ hash = (hash*31 + id.charCodeAt(i)) % 500; }
  const base = 60 + hash;
  return base + (state.likedExercises.includes(id) ? 1 : 0);
}

function toggleLike(id){
  const idx = state.likedExercises.indexOf(id);
  const card = document.querySelector(`.feed-card[data-id="${id}"]`);
  const btn = card ? card.querySelector(".like-btn") : null;
  if(idx === -1){
    state.likedExercises.push(id);
    if(btn){ btn.classList.add("liked"); btn.innerHTML = `❤️<span class="like-count">${likeCount(id)}</span>`; }
  }else{
    state.likedExercises.splice(idx,1);
    if(btn){ btn.classList.remove("liked"); btn.innerHTML = `🤍<span class="like-count">${likeCount(id)}</span>`; }
  }
  saveState();
  updateProfileStats();
}
